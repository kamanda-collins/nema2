
import React, { useState, useRef } from 'react';
import { Card } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Badge } from '@/components/ui/badge';
import { MapPin, Download, FileText, Image, Compass, Scale, Layers } from 'lucide-react';
import { useToast } from '@/hooks/use-toast';
import jsPDF from 'jspdf';

interface ProfessionalMapRendererProps {
  center_point: [number, number];
  features: any[];
  currentShape: any;
}

export const ProfessionalMapRenderer: React.FC<ProfessionalMapRendererProps> = ({
  center_point,
  features,
  currentShape
}) => {
  const [mapTitle, setMapTitle] = useState('Environmental Analysis Map');
  const [mapSubtitle, setMapSubtitle] = useState('Generated by Geo-Labs');
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedMapUrl, setGeneratedMapUrl] = useState<string | null>(null);
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const { toast } = useToast();

  // Function to draw realistic basemap background
  const drawBasemapBackground = async (ctx: CanvasRenderingContext2D, width: number, height: number, centerPoint: [number, number]) => {
    const mapArea = { x: 80, y: 120, width: width - 160, height: height - 240 };
    
    // Create terrain-like gradient
    const gradient = ctx.createRadialGradient(
      mapArea.x + mapArea.width/2, mapArea.y + mapArea.height/2, 0,
      mapArea.x + mapArea.width/2, mapArea.y + mapArea.height/2, mapArea.width/2
    );
    gradient.addColorStop(0, '#8bc34a'); // Green center (land)
    gradient.addColorStop(0.6, '#ffeb3b'); // Yellow (vegetation)
    gradient.addColorStop(0.8, '#795548'); // Brown (terrain)
    gradient.addColorStop(1, '#2196f3'); // Blue (water bodies)
    
    ctx.fillStyle = gradient;
    ctx.fillRect(mapArea.x, mapArea.y, mapArea.width, mapArea.height);
    
    // Add some texture for realism
    ctx.globalAlpha = 0.3;
    for (let i = 0; i < 50; i++) {
      const x = mapArea.x + Math.random() * mapArea.width;
      const y = mapArea.y + Math.random() * mapArea.height;
      const size = Math.random() * 3 + 1;
      
      ctx.fillStyle = Math.random() > 0.5 ? '#4caf50' : '#388e3c';
      ctx.beginPath();
      ctx.arc(x, y, size, 0, 2 * Math.PI);
      ctx.fill();
    }
    ctx.globalAlpha = 1;
    
    // Draw coordinate grid
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.3)';
    ctx.lineWidth = 1;
    for (let i = mapArea.x; i < mapArea.x + mapArea.width; i += 40) {
      ctx.beginPath();
      ctx.moveTo(i, mapArea.y);
      ctx.lineTo(i, mapArea.y + mapArea.height);
      ctx.stroke();
    }
    for (let i = mapArea.y; i < mapArea.y + mapArea.height; i += 40) {
      ctx.beginPath();
      ctx.moveTo(mapArea.x, i);
      ctx.lineTo(mapArea.x + mapArea.width, i);
      ctx.stroke();
    }
  };

  // Function to draw highlighted polygon
  const drawHighlightedPolygon = (ctx: CanvasRenderingContext2D, shape: any, width: number, height: number, centerPoint: [number, number]) => {
    const mapArea = { x: 80, y: 120, width: width - 160, height: height - 240 };
    
    try {
      let coordinates: number[][];
      
      // Handle different geometry types
      if (shape.geometry?.type === 'Polygon') {
        coordinates = shape.geometry.coordinates[0];
      } else if (shape.geometry?.coordinates) {
        coordinates = shape.geometry.coordinates;
      } else {
        // Default to a representative polygon around the center
        const centerX = mapArea.x + mapArea.width / 2;
        const centerY = mapArea.y + mapArea.height / 2;
        const radius = Math.min(mapArea.width, mapArea.height) * 0.3;
        
        coordinates = [];
        for (let i = 0; i < 8; i++) {
          const angle = (i / 8) * 2 * Math.PI;
          coordinates.push([
            centerX + Math.cos(angle) * radius,
            centerY + Math.sin(angle) * radius
          ]);
        }
      }
      
      if (coordinates && coordinates.length > 0) {
        // Convert geographic coordinates to canvas coordinates if needed
        const canvasCoords = coordinates.map(coord => {
          if (coord.length >= 2 && typeof coord[0] === 'number' && typeof coord[1] === 'number') {
            // If these are geographic coordinates (lat/lng), convert them
            if (Math.abs(coord[0]) <= 180 && Math.abs(coord[1]) <= 90) {
              return [
                mapArea.x + ((coord[0] - centerPoint[1] + 0.01) / 0.02) * mapArea.width,
                mapArea.y + mapArea.height - ((coord[1] - centerPoint[0] + 0.01) / 0.02) * mapArea.height
              ];
            }
          }
          return coord;
        });
        
        // Draw filled polygon with transparency
        ctx.fillStyle = 'rgba(255, 152, 0, 0.3)';
        ctx.beginPath();
        ctx.moveTo(canvasCoords[0][0], canvasCoords[0][1]);
        for (let i = 1; i < canvasCoords.length; i++) {
          ctx.lineTo(canvasCoords[i][0], canvasCoords[i][1]);
        }
        ctx.closePath();
        ctx.fill();
        
        // Draw polygon border
        ctx.strokeStyle = '#ff9800';
        ctx.lineWidth = 3;
        ctx.setLineDash([10, 5]);
        ctx.stroke();
        ctx.setLineDash([]);
        
        // Add label
        const labelX = canvasCoords.reduce((sum, coord) => sum + coord[0], 0) / canvasCoords.length;
        const labelY = canvasCoords.reduce((sum, coord) => sum + coord[1], 0) / canvasCoords.length;
        
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(labelX - 40, labelY - 15, 80, 20);
        ctx.strokeStyle = '#ff9800';
        ctx.lineWidth = 2;
        ctx.strokeRect(labelX - 40, labelY - 15, 80, 20);
        
        ctx.fillStyle = '#ff9800';
        ctx.font = 'bold 12px Arial';
        ctx.textAlign = 'center';
        ctx.fillText('Study Area', labelX, labelY);
      }
    } catch (error) {
      console.error('Error drawing polygon:', error);
      // Fallback to simple circle
      const centerX = mapArea.x + mapArea.width / 2;
      const centerY = mapArea.y + mapArea.height / 2;
      const radius = 100;
      
      ctx.fillStyle = 'rgba(255, 152, 0, 0.3)';
      ctx.beginPath();
      ctx.arc(centerX, centerY, radius, 0, 2 * Math.PI);
      ctx.fill();
      
      ctx.strokeStyle = '#ff9800';
      ctx.lineWidth = 3;
      ctx.setLineDash([10, 5]);
      ctx.stroke();
      ctx.setLineDash([]);
    }
  };

  const generateProfessionalMap = async () => {
    setIsGenerating(true);
    toast({
      title: "Generating Professional Map",
      description: "Creating high-quality map with GIS elements..."
    });

    try {
      const canvas = canvasRef.current!;
      const ctx = canvas.getContext('2d')!;
      
      // Set canvas size for high quality output
      canvas.width = 1200;
      canvas.height = 800;
      
      // Clear canvas with white background
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      
      // Draw realistic basemap background
      await drawBasemapBackground(ctx, canvas.width, canvas.height, center_point);
      
      // Draw grid lines for professional appearance
      ctx.strokeStyle = '#e0e0e0';
      ctx.lineWidth = 1;
      for (let i = 80; i < canvas.width - 80; i += 40) {
        ctx.beginPath();
        ctx.moveTo(i, 120);
        ctx.lineTo(i, canvas.height - 120);
        ctx.stroke();
      }
      for (let i = 120; i < canvas.height - 120; i += 40) {
        ctx.beginPath();
        ctx.moveTo(80, i);
        ctx.lineTo(canvas.width - 80, i);
        ctx.stroke();
      }
      
      // Draw highlighted boundary polygon if currentShape exists
      if (currentShape && currentShape.geometry) {
        drawHighlightedPolygon(ctx, currentShape, canvas.width, canvas.height, center_point);
      }
      
      // Draw features as points
      features.forEach((feature, index) => {
        const x = 200 + (index * 150) % 600;
        const y = 200 + Math.floor(index / 4) * 100;
        
        ctx.fillStyle = '#2196f3';
        ctx.beginPath();
        ctx.arc(x, y, 6, 0, 2 * Math.PI);
        ctx.fill();
        
        ctx.fillStyle = '#ffffff';
        ctx.beginPath();
        ctx.arc(x, y, 3, 0, 2 * Math.PI);
        ctx.fill();
        
        ctx.fillStyle = '#333333';
        ctx.font = '10px Arial';
        ctx.textAlign = 'center';
        ctx.fillText(feature.name.substring(0, 15), x, y + 20);
      });
      
      // Draw center point marker
      const markerX = canvas.width / 2;
      const markerY = canvas.height / 2;
      
      ctx.fillStyle = '#ea4335';
      ctx.beginPath();
      ctx.arc(markerX, markerY, 8, 0, 2 * Math.PI);
      ctx.fill();
      
      ctx.fillStyle = '#ffffff';
      ctx.beginPath();
      ctx.arc(markerX, markerY, 4, 0, 2 * Math.PI);
      ctx.fill();
      
      // Draw title
      ctx.fillStyle = '#1a1a1a';
      ctx.font = 'bold 32px Arial';
      ctx.textAlign = 'center';
      ctx.fillText(mapTitle, canvas.width / 2, 50);
      
      // Draw subtitle
      ctx.font = '18px Arial';
      ctx.fillStyle = '#666666';
      ctx.fillText(mapSubtitle, canvas.width / 2, 80);
      
      // Draw coordinates
      ctx.font = '14px Arial';
      ctx.textAlign = 'left';
      ctx.fillStyle = '#333333';
      ctx.fillText(`Center: ${center_point[0].toFixed(4)}°, ${center_point[1].toFixed(4)}°`, 100, canvas.height - 80);
      ctx.fillText(`Generated: ${new Date().toLocaleDateString()}`, 100, canvas.height - 60);
      ctx.fillText(`Features: ${features.length}`, 100, canvas.height - 40);
      
      // Draw north arrow
      const northX = canvas.width - 120;
      const northY = 180;
      
      ctx.fillStyle = '#1a1a1a';
      ctx.beginPath();
      ctx.moveTo(northX, northY - 20);
      ctx.lineTo(northX - 10, northY + 10);
      ctx.lineTo(northX, northY + 5);
      ctx.lineTo(northX + 10, northY + 10);
      ctx.closePath();
      ctx.fill();
      
      ctx.font = 'bold 16px Arial';
      ctx.textAlign = 'center';
      ctx.fillText('N', northX, northY + 35);
      
      // Draw scale bar
      const scaleX = 100;
      const scaleY = canvas.height - 140;
      const scaleWidth = 100;
      
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(scaleX, scaleY, scaleWidth, 20);
      ctx.strokeStyle = '#1a1a1a';
      ctx.lineWidth = 2;
      ctx.strokeRect(scaleX, scaleY, scaleWidth, 20);
      
      ctx.fillStyle = '#1a1a1a';
      ctx.fillRect(scaleX, scaleY, scaleWidth / 2, 20);
      
      ctx.font = '12px Arial';
      ctx.textAlign = 'center';
      ctx.fillText('1 km', scaleX + scaleWidth / 2, scaleY + 35);
      
      // Draw legend
      const legendX = canvas.width - 200;
      const legendY = 250;
      
      ctx.fillStyle = 'rgba(255, 255, 255, 0.9)';
      ctx.fillRect(legendX, legendY, 180, 120);
      ctx.strokeStyle = '#1a1a1a';
      ctx.lineWidth = 1;
      ctx.strokeRect(legendX, legendY, 180, 120);
      
      ctx.fillStyle = '#1a1a1a';
      ctx.font = 'bold 14px Arial';
      ctx.textAlign = 'left';
      ctx.fillText('Legend', legendX + 10, legendY + 20);
      
      // Legend items
      ctx.fillStyle = '#ea4335';
      ctx.fillRect(legendX + 10, legendY + 35, 15, 15);
      ctx.fillStyle = '#1a1a1a';
      ctx.font = '12px Arial';
      ctx.fillText('Center Point', legendX + 35, legendY + 47);
      
      ctx.fillStyle = '#2196f3';
      ctx.fillRect(legendX + 10, legendY + 60, 15, 15);
      ctx.fillText('Features', legendX + 35, legendY + 72);
      
      if (currentShape) {
        ctx.strokeStyle = '#d32f2f';
        ctx.lineWidth = 2;
        ctx.setLineDash([5, 3]);
        ctx.strokeRect(legendX + 10, legendY + 85, 15, 15);
        ctx.setLineDash([]);
        ctx.fillStyle = '#1a1a1a';
        ctx.fillText('Study Area', legendX + 35, legendY + 97);
      }
      
      // Convert canvas to data URL
      const dataUrl = canvas.toDataURL('image/png');
      setGeneratedMapUrl(dataUrl);
      
      toast({
        title: "Professional Map Generated",
        description: "High-quality map ready for download"
      });
      
    } catch (error) {
      console.error('Map generation error:', error);
      toast({
        title: "Generation Failed",
        description: "Error generating professional map",
        variant: "destructive"
      });
    } finally {
      setIsGenerating(false);
    }
  };

  const downloadMap = (format: 'png' | 'pdf') => {
    if (!generatedMapUrl) return;
    
    if (format === 'png') {
      const link = document.createElement('a');
      link.href = generatedMapUrl;
      link.download = `professional-map-${Date.now()}.png`;
      link.click();
    } else if (format === 'pdf') {
      const pdf = new jsPDF({
        orientation: 'landscape',
        unit: 'mm',
        format: 'a3'
      });
      
      pdf.addImage(generatedMapUrl, 'PNG', 10, 10, 400, 267);
      pdf.save(`professional-map-${Date.now()}.pdf`);
    }
  };

  return (
    <Card className="p-6 bg-gradient-to-br from-blue-50 to-indigo-50">
      <div className="flex items-center gap-3 mb-4">
        <MapPin className="h-6 w-6 text-blue-600" />
        <h3 className="text-xl font-semibold text-gray-900">Professional Map Generator</h3>
        <Badge variant="outline" className="bg-blue-100 text-blue-800">GIS Quality</Badge>
      </div>
      
      <div className="space-y-4">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <div>
            <label className="block text-sm font-medium mb-2">Map Title</label>
            <Input
              value={mapTitle}
              onChange={(e) => setMapTitle(e.target.value)}
              placeholder="Enter map title"
            />
          </div>
          <div>
            <label className="block text-sm font-medium mb-2">Subtitle</label>
            <Input
              value={mapSubtitle}
              onChange={(e) => setMapSubtitle(e.target.value)}
              placeholder="Enter subtitle"
            />
          </div>
        </div>
        
        <div className="flex gap-2">
          <Button
            onClick={generateProfessionalMap}
            disabled={isGenerating}
            className="flex items-center gap-2"
          >
            {isGenerating ? (
              <>
                <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
                Generating...
              </>
            ) : (
              <>
                <Layers className="h-4 w-4" />
                Generate Professional Map
              </>
            )}
          </Button>
          
          {generatedMapUrl && (
            <>
              <Button
                onClick={() => downloadMap('png')}
                variant="outline"
                className="flex items-center gap-2"
              >
                <Image className="h-4 w-4" />
                PNG
              </Button>
              <Button
                onClick={() => downloadMap('pdf')}
                variant="outline"
                className="flex items-center gap-2"
              >
                <FileText className="h-4 w-4" />
                PDF
              </Button>
            </>
          )}
        </div>
        
        <canvas
          ref={canvasRef}
          className="hidden"
        />
        
        {generatedMapUrl && (
          <div className="mt-6">
            <h4 className="font-medium mb-2">Generated Professional Map</h4>
            <div className="border rounded-lg overflow-hidden shadow-lg">
              <img
                src={generatedMapUrl}
                alt="Professional Map"
                className="w-full h-auto"
              />
            </div>
            <div className="mt-2 flex items-center gap-4 text-sm text-gray-600">
              <div className="flex items-center gap-1">
                <Compass className="h-4 w-4" />
                North Arrow
              </div>
              <div className="flex items-center gap-1">
                <Scale className="h-4 w-4" />
                Scale Bar
              </div>
              <div className="flex items-center gap-1">
                <Layers className="h-4 w-4" />
                Legend
              </div>
            </div>
          </div>
        )}
      </div>
    </Card>
  );
};
