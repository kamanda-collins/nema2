
import React, { useState } from 'react';
import { Card } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Progress } from '@/components/ui/progress';
import { Badge } from '@/components/ui/badge';
import { useToast } from '@/hooks/use-toast';
import { supabase } from '@/integrations/supabase/client';
import { Database, MapPin, BarChart3, FileText, Download, Upload } from 'lucide-react';

interface ProcessingJob {
  id: string;
  type: 'analysis' | 'export' | 'processing';
  status: 'pending' | 'running' | 'completed' | 'failed';
  progress: number;
  result?: any;
}

export const GeospatialProcessor: React.FC = () => {
  const [jobs, setJobs] = useState<ProcessingJob[]>([]);
  const [isProcessing, setIsProcessing] = useState(false);
  const { toast } = useToast();

  const startVolumeCalculation = async (geometry: any) => {
    setIsProcessing(true);
    const jobId = Date.now().toString();
    
    const newJob: ProcessingJob = {
      id: jobId,
      type: 'analysis',
      status: 'pending',
      progress: 0
    };
    
    setJobs(prev => [...prev, newJob]);

    try {
      // Call PostGIS volume calculation
      const { data, error } = await supabase.functions.invoke('geospatial-processing', {
        body: {
          operation_type: 'volume_calculation',
          geometry_data: geometry,
          parameters: {
            elevation_model: 'srtm',
            calculation_method: 'triangulation'
          }
        }
      });

      if (error) throw error;

      // Update job status
      setJobs(prev => prev.map(job => 
        job.id === jobId 
          ? { ...job, status: 'completed', progress: 100, result: data }
          : job
      ));

      toast({
        title: "Volume calculation completed",
        description: `Calculated volume: ${data?.volume || 'N/A'} cubic meters`,
      });

    } catch (error) {
      console.error('Volume calculation failed:', error);
      setJobs(prev => prev.map(job => 
        job.id === jobId 
          ? { ...job, status: 'failed', progress: 0 }
          : job
      ));
      
      toast({
        title: "Processing failed",
        description: "Failed to calculate volume",
        variant: "destructive",
      });
    } finally {
      setIsProcessing(false);
    }
  };

  const generateProfessionalReport = async (analysisData: any) => {
    setIsProcessing(true);
    const jobId = Date.now().toString();
    
    const newJob: ProcessingJob = {
      id: jobId,
      type: 'export',
      status: 'pending',
      progress: 0
    };
    
    setJobs(prev => [...prev, newJob]);

    try {
      const { data, error } = await supabase.functions.invoke('generate-professional-map', {
        body: {
          map_name: 'Environmental Analysis Report',
          map_type: 'environmental',
          boundary: analysisData?.boundary,
          center_point: analysisData?.center,
          zoom_level: 12,
          style_config: {
            base_layer: 'satellite',
            color_scheme: 'professional',
            legend_position: 'bottom-right',
            scale_bar: true,
            north_arrow: true,
            title: 'Environmental Analysis Report',
            subtitle: 'Generated by Geo-Labs'
          },
          export_formats: ['pdf', 'png']
        }
      });

      if (error) throw error;

      setJobs(prev => prev.map(job => 
        job.id === jobId 
          ? { ...job, status: 'completed', progress: 100, result: data }
          : job
      ));

      toast({
        title: "Report generation completed",
        description: "Professional report has been generated",
      });

    } catch (error) {
      console.error('Report generation failed:', error);
      setJobs(prev => prev.map(job => 
        job.id === jobId 
          ? { ...job, status: 'failed', progress: 0 }
          : job
      ));
      
      toast({
        title: "Report generation failed",
        description: "Failed to generate professional report",
        variant: "destructive",
      });
    } finally {
      setIsProcessing(false);
    }
  };

  const runEnvironmentalAnalysis = async (location: any, dateRange: any) => {
    setIsProcessing(true);
    const jobId = Date.now().toString();
    
    const newJob: ProcessingJob = {
      id: jobId,
      type: 'processing',
      status: 'pending',
      progress: 0
    };
    
    setJobs(prev => [...prev, newJob]);

    try {
      const { data, error } = await supabase.functions.invoke('environmental-analysis', {
        body: {
          analysis_type: 'environmental_change',
          location: location,
          start_date: dateRange.start,
          end_date: dateRange.end,
          data_sources: ['sentinel-2', 'landsat-8']
        }
      });

      if (error) throw error;

      setJobs(prev => prev.map(job => 
        job.id === jobId 
          ? { ...job, status: 'completed', progress: 100, result: data }
          : job
      ));

      toast({
        title: "Environmental analysis completed",
        description: "Analysis results are ready for review",
      });

    } catch (error) {
      console.error('Environmental analysis failed:', error);
      setJobs(prev => prev.map(job => 
        job.id === jobId 
          ? { ...job, status: 'failed', progress: 0 }
          : job
      ));
      
      toast({
        title: "Analysis failed",
        description: "Failed to complete environmental analysis",
        variant: "destructive",
      });
    } finally {
      setIsProcessing(false);
    }
  };

  const getStatusColor = (status: string) => {
    switch (status) {
      case 'completed': return 'bg-green-100 text-green-800';
      case 'running': return 'bg-blue-100 text-blue-800';
      case 'failed': return 'bg-red-100 text-red-800';
      default: return 'bg-gray-100 text-gray-800';
    }
  };

  const getTypeIcon = (type: string) => {
    switch (type) {
      case 'analysis': return <BarChart3 className="h-4 w-4" />;
      case 'export': return <FileText className="h-4 w-4" />;
      case 'processing': return <Database className="h-4 w-4" />;
      default: return <MapPin className="h-4 w-4" />;
    }
  };

  return (
    <div className="space-y-6">
      <Card className="p-6">
        <h3 className="text-lg font-semibold mb-4 flex items-center gap-2">
          <Database className="h-5 w-5" />
          Backend Processing Center
        </h3>
        
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4 mb-6">
          <Button 
            onClick={() => startVolumeCalculation(null)}
            disabled={isProcessing}
            className="flex items-center gap-2"
          >
            <BarChart3 className="h-4 w-4" />
            Volume Analysis
          </Button>
          
          <Button 
            onClick={() => generateProfessionalReport(null)}
            disabled={isProcessing}
            className="flex items-center gap-2"
          >
            <FileText className="h-4 w-4" />
            Generate Report
          </Button>
          
          <Button 
            onClick={() => runEnvironmentalAnalysis(null, { start: '2023-01-01', end: '2023-12-31' })}
            disabled={isProcessing}
            className="flex items-center gap-2"
          >
            <Upload className="h-4 w-4" />
            Environmental Analysis
          </Button>
        </div>

        {/* Processing Jobs */}
        <div className="space-y-3">
          <h4 className="font-medium">Active Jobs</h4>
          {jobs.length === 0 ? (
            <p className="text-gray-500 text-sm">No active processing jobs</p>
          ) : (
            jobs.map((job) => (
              <div key={job.id} className="flex items-center justify-between p-3 border rounded-lg">
                <div className="flex items-center gap-3">
                  {getTypeIcon(job.type)}
                  <div>
                    <div className="flex items-center gap-2">
                      <span className="font-medium">Job #{job.id.slice(-4)}</span>
                      <Badge className={getStatusColor(job.status)}>
                        {job.status.toUpperCase()}
                      </Badge>
                    </div>
                    <p className="text-sm text-gray-600">
                      {job.type === 'analysis' && 'Volume calculation and terrain analysis'}
                      {job.type === 'export' && 'Professional report generation'}
                      {job.type === 'processing' && 'Environmental change detection'}
                    </p>
                  </div>
                </div>
                
                <div className="flex items-center gap-3">
                  {job.status === 'running' && (
                    <Progress value={job.progress} className="w-20" />
                  )}
                  {job.status === 'completed' && job.result && (
                    <Button variant="outline" size="sm">
                      <Download className="h-4 w-4 mr-2" />
                      Download
                    </Button>
                  )}
                </div>
              </div>
            ))
          )}
        </div>
      </Card>
    </div>
  );
};
