
import { requestProfessionalMap } from './professionalMapBackend';
import jsPDF from 'jspdf';

interface ProfessionalMapExportParams {
  searchLocation: { lat: number; lng: number; name: string };
  currentShape?: any;
  features: any[];
  toast: (options: { title: string; description?: string }) => void;
}

export async function exportProfessionalMap({ searchLocation, currentShape, features, toast }: ProfessionalMapExportParams) {
  toast({
    title: "Exporting Professional Map",
    description: "Contacting backend for professional-grade map rendering...",
  });

  const { url, error } = await requestProfessionalMap({
    center: [searchLocation.lat, searchLocation.lng],
    zoom: 12,
    style_config: {
      base_layer: 'satellite',
      color_scheme: 'professional',
      legend_position: 'bottom-right',
      scale_bar: true,
      north_arrow: true,
      title: `Professional Map - ${searchLocation.name.split(',')[0]}`,
      subtitle: 'Generated by Geo-Labs'
    },
    features: features.slice(0, 10),
    boundary: currentShape ? currentShape.geometry : undefined,
    format: 'pdf',
  });

  if (error) {
    toast({
      title: "Professional Backend Not Integrated",
      description: "Professional map rendering will be available once you connect a Python backend (see project instructions).",
    });
    throw new Error(error);
  } else if (url) {
    // Download PDF from URL or process as needed (real backend integration)
    toast({
      title: "Professional Map Download",
      description: "Professional map has been rendered and will be downloaded.",
    });
    window.open(url, "_blank");
    return true;
  }
}
